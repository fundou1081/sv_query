#!/usr/bin/env python3
"""Generate the result-key JSON schema from the CLI registry contract.

The registry (`sv_query.cli._registry.JSON_CONTRACT`) is the single source for
per-command result fields. This generator makes the machine-readable schema a
derived artifact; `--check` fails on drift.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
OUT = ROOT / "tools" / "generated_result_schema.json"


def build() -> dict:
    sys.path.insert(0, str(SRC))
    from sv_query.cli._registry import JSON_CONTRACT

    commands = {}
    for name, contract in sorted(JSON_CONTRACT["commands"].items()):
        if "result_fields" in contract:
            optional = list(contract.get("optional_result_fields", ()))
            required = [f for f in contract["result_fields"] if f not in optional]
            props = list(dict.fromkeys([*contract["result_fields"], *optional]))
        elif "base_fields" in contract:
            required = list(contract["base_fields"])
            props = list(required)
            for fields in contract.get("modes", {}).values():
                props.extend(f for f in fields if f not in props)
            props.extend(f for f in contract.get("optional_fields", ()) if f not in props)
            optional = sorted(f for f in props if f not in required)
        else:
            ref = contract.get("fields")
            definition = JSON_CONTRACT.get(ref, {}) if isinstance(ref, str) else {}
            props = list(definition) if isinstance(definition, dict) else []
            required, optional = [], props
        commands[name] = {
            "required": required,
            "optional": sorted(optional),
            "properties": {f: {} for f in props},
        }
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://github.com/fundou1081/sv_query/tools/generated_result_schema.json",
        "title": "sv_query command result keys (generated)",
        "description": "Generated by tools/gen_result_schema.py from JSON_CONTRACT; do not edit.",
        "schema_version": JSON_CONTRACT["schema_version"],
        "commands": commands,
    }


def render() -> str:
    return json.dumps(build(), indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if output drifts")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
        if current != text:
            print(f"FAIL\t{OUT.relative_to(ROOT)} is stale; run tools/gen_result_schema.py")
            return 1
        print("result-schema: PASS (generated artifact in sync)")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
